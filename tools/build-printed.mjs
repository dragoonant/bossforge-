// Regenerates data/cards.js (mechanical fields) and data/printed.js (printed names and text)
// from the wiki dump in scratch/wiki/list.json (see docs/sources.md). Never hand-edit either
// output. Only the Base Set table (BMR001-BMR096) crosses into data/ (PLAN D3).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const wikitext = JSON.parse(readFileSync(join(root, 'scratch/wiki/list.json'), 'utf8')).parse.wikitext['*'];

const start = wikitext.indexOf('==Base Set==');
const end = wikitext.indexOf('\n==', start + 5);
if (start < 0 || end < 0) throw new Error('Base Set section not found in the wiki dump');
const section = wikitext.slice(start, end);

const clean = (s) =>
  s
    .replace(/\[\[(?:[^|\]]*\|)?([^\]]*)\]\]/g, '$1')
    .replace(/'''|''/g, '')
    .replace(/<br\s*\/?>/g, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();

const TREASURE = { Cleric: 'cleric', Fighter: 'fighter', Mage: 'mage', Thief: 'thief' };
const treasures = (s) => {
  if (s === '-' || s === '?') return [];
  const out = [];
  for (const part of s.split('+').map((x) => x.trim())) {
    const m = part.match(/^(Cleric|Fighter|Mage|Thief)(?:\*(\d))?$/);
    if (!m) throw new Error(`Unknown treasure "${s}"`);
    for (let i = 0; i < Number(m[2] ?? 1); i++) out.push(TREASURE[m[1]]);
  }
  return out;
};

const cards = {};
const printed = {};
const rows = section.split(/\n\|-\s*\n/);
for (let raw of rows) {
  raw = raw.trim();
  if (!/^\|\s*BMR\d{3}/.test(raw)) continue;
  // A piped link [[page|shown]] prints the shown half on the card.
  const heroName = raw.match(/'''\[\[([^\]]+)\]\]'''/)?.[1]?.split('|').pop();
  const cells = raw.replace(/\n\|(?!-)/g, '||').replace(/^\|/, '').split('||').map(clean);
  if (cells.length < 9) throw new Error(`Short row: ${raw.slice(0, 80)}`);
  const [id, name, subtitle, stat, treasure, type, text, minPlayers, qtyCell] = cells;
  const qty = Number(qtyCell.match(/\d+/)[0]);
  if (type === 'Boss') {
    cards[id] = { id, kind: 'boss', xp: Number(stat), treasure: treasures(treasure), qty };
    printed[id] = { name, subtitle, text };
  } else if (type === 'Room') {
    const adv = subtitle.startsWith('Advanced');
    const sub = subtitle.includes('Monster') ? 'monster' : 'trap';
    cards[id] = { id, kind: 'room', sub, adv, dmg: stat === '*' ? null : Number(stat), treasure: treasures(treasure), qty };
    // The wiki carries a later printing's wording after "Revised:" (RULING R12).
    const revised = text.split(/Revised:\s*/);
    printed[id] = { name, text: (revised[1] ?? revised[0]).trim() };
  } else if (type === 'Spell') {
    const phase = { Build: 'build', Adventure: 'adventure', 'Build & Adventure': 'both' }[stat];
    if (!phase) throw new Error(`Unknown spell phase "${stat}" on ${id}`);
    cards[id] = { id, kind: 'spell', phase, qty };
    printed[id] = { name, text };
  } else if (type === 'Hero') {
    const epic = subtitle === 'Epic Hero';
    const fool = name === 'The Fool';
    cards[id] = { id, kind: 'hero', epic, health: Number(stat), treasure: treasures(treasure), minPlayers: Number(minPlayers), qty };
    if (fool) printed[id] = { name, text };
    else {
      if (!heroName) throw new Error(`No hero name on ${id}`);
      printed[id] = { name: heroName, flavor: text.slice(heroName.length).trim() };
    }
  } else throw new Error(`Unknown type "${type}" on ${id}`);
}

const count = (k) => Object.values(cards).filter((c) => c.kind === k).reduce((n, c) => n + c.qty, 0);
const totals = { boss: count('boss'), room: count('room'), spell: count('spell'), hero: count('hero') };
// RB p3 deck contents for the Base Set: 8 Bosses (original printing), 75 Rooms, 31 Spells, 41 Heroes.
const expected = { boss: 8, room: 75, spell: 31, hero: 41 };
for (const k of Object.keys(expected)) {
  if (totals[k] !== expected[k]) throw new Error(`${k}: ${totals[k]} cards, expected ${expected[k]}`);
}

const banner = (what) =>
  `// GENERATED by tools/build-printed.mjs from the Boss Monster wiki dump (docs/sources.md).\n` +
  `// Never hand-edit. ${what}\n`;
writeFileSync(
  join(root, 'data/cards.js'),
  banner('Mechanical card data for the Base Set (BMR001-BMR096).') +
    `(function () {\n  'use strict';\n  globalThis.BF = globalThis.BF || {};\n  BF.CARD_DATA = ${JSON.stringify(cards, null, 1).replace(/\n\s*/g, ' ')};\n})();\n`,
);
writeFileSync(
  join(root, 'data/printed.js'),
  banner('Printed names and rules text, (c) Brotherwise Games. Deleting this file is the withdrawal lever (docs/takedown.md).') +
    `(function () {\n  'use strict';\n  globalThis.BF = globalThis.BF || {};\n  BF.PRINTED = {\n` +
    Object.entries(printed)
      .map(([id, p]) => `    ${id}: ${JSON.stringify(p)},`)
      .join('\n') +
    `\n  };\n})();\n`,
);
console.log(`cards: ${Object.keys(cards).length} unique, ${JSON.stringify(totals)}`);
